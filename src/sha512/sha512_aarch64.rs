//! the round-constant sum for the current message word is formed, rotated and
//! added to the fourth state vector, `sha512h` mixes it with the `ext`-shifted
//! neighbouring state words, and `sha512h2` produces the new fourth word while
//! the second word absorbs the intermediate. State roles rotate right every
//! step, so the vectors are passed by number rather than moved. `sched!`
//! extends the message schedule one step ahead of its use, so its latency
//! hides behind the hash chain. This ordering runs ~4% faster than LLVM's
