/// Two rounds: `$t` receives the new fourth state word, `$nb` the new
/// second word; `$w` is the scheduled message word for these rounds, `$k`
/// holds their constants and `$kn` receives the next pair's.
macro_rules! step {
    (
        $t:literal,
        $a:literal,
        $b:literal,
        $c:literal,
        $d:literal,
        $nb:literal,
        $w:literal,
        $k:literal,
        $kn:literal
    ) => {
        concat!(
            "add v",
            $t,
            ".2d, v",
            $w,
            ".2d, v",
            $k,
            ".2d\n",
            "ld1 {{v",
            $kn,
            ".2d}}, [x3], #16\n",
            "ext v",
            $t,
            ".16b, v",
            $t,
            ".16b, v",
            $t,
            ".16b, #8\n",
            "ext v4.16b, v",
            $c,
            ".16b, v",
            $d,
            ".16b, #8\n",
            "ext v5.16b, v",
            $b,
            ".16b, v",
            $c,
            ".16b, #8\n",
            "add v",
            $t,
            ".2d, v",
            $t,
            ".2d, v",
            $d,
            ".2d\n",
            "sha512h q",
            $t,
            ", q4, v5.2d\n",
            "add v",
            $nb,
            ".2d, v",
            $b,
            ".2d, v",
            $t,
            ".2d\n",
            "sha512h2 q",
            $t,
            ", q",
            $b,
            ", v",
            $a,
            ".2d\n",
        )
    };
}

