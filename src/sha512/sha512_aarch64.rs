/// Message schedule: `W[j] += sigma0(W[j+1]) + W[j+9] + sigma1(W[j+14])`
/// on the eight two-word vectors, i.e. `$w` from `$w1`, `$w7` and the
/// odd/even straddle of `$w4`/`$w5`.
macro_rules! sched {
    ($w:literal, $w1:literal, $w4:literal, $w5:literal, $w7:literal) => {
        concat!(
            "sha512su0 v",
            $w,
            ".2d, v",
            $w1,
            ".2d\n",
            "ext v2.16b, v",
            $w4,
            ".16b, v",
            $w5,
            ".16b, #8\n",
            "sha512su1 v",
            $w,
            ".2d, v",
            $w7,
            ".2d, v2.2d\n",
        )
    };
}

